// Generates js/land.js: Natural Earth land (via world-atlas), clipped to the map
// bounds and projected to SVG units. Run with `npm run build:map`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));

// Keep in sync with PROJ in js/data.js.
const LON0 = 31, LAT1 = 35, LON1 = 61, LAT0 = 10, S = 40;
const KX = Math.cos((23 * Math.PI) / 180);
const proj = ([lon, lat]) => [(lon - LON0) * KX * S, (LAT1 - lat) * S];

// Sutherland-Hodgman clip against a slightly padded lon/lat box.
const PAD = 14;
const box = [LON0 - PAD, LAT0 - PAD, LON1 + PAD, LAT1 + PAD];
function clip(ring) {
  const edges = [
    [(p) => p[0] >= box[0], (a, b) => [box[0], a[1] + ((b[1] - a[1]) * (box[0] - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= box[2], (a, b) => [box[2], a[1] + ((b[1] - a[1]) * (box[2] - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= box[1], (a, b) => [a[0] + ((b[0] - a[0]) * (box[1] - a[1])) / (b[1] - a[1]), box[1]]],
    [(p) => p[1] <= box[3], (a, b) => [a[0] + ((b[0] - a[0]) * (box[3] - a[1])) / (b[1] - a[1]), box[3]]],
  ];
  let out = ring;
  for (const [inside, cut] of edges) {
    const input = out;
    out = [];
    for (let i = 0; i < input.length; i++) {
      const cur = input[i], prev = input[(i + input.length - 1) % input.length];
      if (inside(cur)) {
        if (!inside(prev)) out.push(cut(prev, cur));
        out.push(cur);
      } else if (inside(prev)) out.push(cut(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}

const land = feature(topo, topo.objects.land);
const geoms = land.type === "FeatureCollection" ? land.features.map((f) => f.geometry) : [land.geometry];
const polys = geoms.flatMap((g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates));
let d = "";
for (const poly of polys) {
  for (const ring of poly) {
    const c = clip(ring);
    if (c.length < 3) continue;
    d += "M" + c.map((p) => proj(p).map((v) => v.toFixed(1)).join(" ")).join("L") + "Z";
  }
}

writeFileSync(
  new URL("../js/land.js", import.meta.url),
  `// Generated by tools/build-land.mjs from Natural Earth (world-atlas land-50m). Do not edit.\nwindow.SEERAH = window.SEERAH || {};\nSEERAH.landPath = "${d}";\n`
);
console.log("land path bytes:", d.length);
